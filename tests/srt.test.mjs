import assert from "node:assert/strict";
import * as m from "../src/features/subtitles/srt.ts";
const src = "﻿1\r\n00:00:01,000 --> 00:00:02,500\r\nআমি বাংলায়\r\nকথা বলি\r\n\r\n2\r\n00:00:03,000 --> 00:01:04,005\r\nHello\r\n";
const segs = m.parseSubtitles(src);
assert.equal(segs.length, 2);
assert.equal(segs[0].text, "আমি বাংলায়\nকথা বলি");
assert.equal(segs[1].end, 64005);
assert.equal(m.formatSrt(segs).split("\n")[1], "00:00:01,000 --> 00:00:02,500");
const vtt = m.formatVtt(segs);
assert.ok(vtt.startsWith("WEBVTT\n\n00:00:01.000"));
assert.deepEqual(m.parseSubtitles(vtt).map((s) => [s.start, s.end]), segs.map((s) => [s.start, s.end]));
assert.equal(m.parseTime("01:02.5"), 62500);
assert.equal(m.parseTime("bad"), null);
assert.equal(m.shiftAll(segs, -5000)[0].start, 0);
const sp = m.splitSegment([{ start: 0, end: 1000, text: "abcd efgh" }], 0, 4);
assert.equal(sp.length, 2); assert.equal(sp[0].end, 500);
assert.equal(m.mergeWithNext(sp, 0).length, 1);
assert.deepEqual(m.replaceAll([{ start: 0, end: 1, text: "Foo foo" }], "foo", "x", false), { segs: [{ start: 0, end: 1, text: "x x" }], count: 2 });
assert.deepEqual(m.findProblems([{ start: 0, end: 2000, text: "" }, { start: 1000, end: 3000, text: "" }]), [0]);
console.log("srt tests ok");
